def canonical_json(value):
    return json.dumps(
        value,
        allow_nan=False,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def sha256(content):
    return hashlib.sha256(content).hexdigest()


def git_blob(content):
    return hashlib.sha1(
        b"blob " + str(len(content)).encode("ascii") + b"\0" + content
    ).hexdigest()


def lp(content):
    return len(content).to_bytes(8, "big") + content


def command_environment_sha256(mapping):
    records = sorted(
        ((name.encode("utf-8"), value.encode("utf-8"))
         for name, value in mapping.items()),
        key=lambda item: item[0],
    )
    payload = bytearray(b"SchurVIO-CP2-command-environment-v1\0")
    payload.extend(len(records).to_bytes(8, "big"))
    for name, value in records:
        payload.extend(lp(name))
        payload.extend(lp(value))
    return sha256(bytes(payload))


def utc(second):
    if not 0 <= second < 60:
        raise ValueError("synthetic UTC second leaves its fixed minute")
    return "2026-01-01T00:00:{:02d}.000000Z".format(second)


def encode_snapshot(root_tag, exists, entries, context=None):
    payload = bytearray(b"SchurVIO-CP2-readiness-snapshot-v1\0")
    payload.extend(lp(root_tag.encode("ascii")))
    payload.extend(b"\1" if exists else b"\0")
    ordered = sorted(entries, key=lambda item: item["path"].encode("utf-8"))
    payload.extend(len(ordered).to_bytes(8, "big"))
    for entry in ordered:
        payload.extend(lp(entry["path"].encode("utf-8")))
        payload.extend(entry["entry_type"].encode("ascii"))
        payload.extend(entry["mode"].to_bytes(8, "big"))
        payload.extend(entry["size"].to_bytes(8, "big"))
        payload.extend(bytes.fromhex(entry["sha256"]))
    if root_tag in ("source", "post_lock"):
        if context is None:
            raise ValueError("source-like snapshot requires a context")
        payload.extend(bytes.fromhex(context["commit"]))
        payload.extend(bytes.fromhex(context["tree"]))
        payload.extend(bytes.fromhex(context["index_tree"]))
        payload.extend(lp(b""))
        for entrypoint in context["entrypoints"]:
            payload.extend(lp(entrypoint["path"].encode("utf-8")))
            payload.extend(bytes.fromhex(entrypoint["git_blob"]))
            payload.extend(bytes.fromhex(entrypoint["sha256"]))
    return bytes(payload)


def passing_self_test_result(entrypoint, names, index):
    cases = []
    for case_index, name in enumerate(names):
        negative = name != "valid_minimal_fixture"
        cases.append({
            "index": case_index,
            "name": name,
            "expected_rejection": negative,
            "observed_rejection": negative,
            "passed": True,
        })
    return {
        "schema_version": 1,
        "record_type": "self_test_result",
        "entrypoint": entrypoint,
        "temporary_root": "/tmp/cp2-actual-readiness-selftest-{}".format(index),
        "bag_provider_calls": 0,
        "cases": cases,
        "case_count": len(cases),
        "passed": True,
    }


