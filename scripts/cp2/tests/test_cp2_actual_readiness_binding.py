    @staticmethod
    def _start_python(source):
        return subprocess.Popen(
            ["/usr/bin/python3", "-I", "-B", "-c", source],
            cwd="/tmp",
            env={"PATH": "/usr/bin:/bin", "LANG": "C", "LC_ALL": "C"},
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
            close_fds=True,
        )

    def test_owned_process_group_timeout_is_reaped(self):
        process = self._start_python("import time; time.sleep(60)")
        return_code, timed_out, descendants = (
            verify_report._actual_wait_owned_process_group(
                process, 0.02, "synthetic timeout child"
            )
        )
        self.assertTrue(timed_out)
        self.assertFalse(descendants)
        self.assertLess(return_code, 0)
        self.assertFalse(verify_report._actual_process_group_exists(process.pid))

    def test_owned_process_group_baseexception_is_reaped(self):
        process = self._start_python("import time; time.sleep(60)")
        real_wait = process.wait
        calls = [0]

        def interrupted_wait(*args, **kwargs):
            calls[0] += 1
            if calls[0] == 1:
                raise KeyboardInterrupt("synthetic wait interruption")
            return real_wait(*args, **kwargs)

        process.wait = interrupted_wait
        with self.assertRaises(KeyboardInterrupt):
            verify_report._actual_wait_owned_process_group(
                process, 1.0, "synthetic interrupted child"
            )
        self.assertIsNotNone(process.returncode)
        self.assertFalse(verify_report._actual_process_group_exists(process.pid))

    def test_owned_process_group_stubborn_descendant_is_detected(self):
        source = (
            "import os,time\n"
            "child=os.fork()\n"
            "if child==0:\n"
            " signal=None\n"
            " time.sleep(60)\n"
            "os._exit(0)\n"
        )
        process = self._start_python(source)
        return_code, timed_out, descendants = (
            verify_report._actual_wait_owned_process_group(
                process, 2.0, "synthetic descendant child"
            )
        )
        self.assertEqual(return_code, 0)
        self.assertFalse(timed_out)
        self.assertTrue(descendants)
        self.assertFalse(verify_report._actual_process_group_exists(process.pid))


