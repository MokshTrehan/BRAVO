    def test_local_module_loader_binding_rejections(self):
        binding = {}
        for name, relative in verify_report._ACTUAL_LOCAL_MODULE_PATHS.items():
            path = CP2_DIRECTORY / Path(relative).name
            status_value = path.lstat()
            binding[name] = {
                "mode": 0o100755 if status_value.st_mode & 0o100 else 0o100644,
                "sha256": sha256(path.read_bytes()),
                "size": status_value.st_size,
            }

        def require_rejection(label, installed, cache, name):
            with self.subTest(binding=label), \
                 mock.patch.object(
                     verify_report, "_ACTUAL_MODULE_SOURCE_BINDING", installed
                 ), \
                 mock.patch.object(
                     verify_report,
                     "_ACTUAL_MODULE_SOURCE_BINDING_ORIGIN",
                     None if installed is None else "artifact_source_context",
                 ), \
                 mock.patch.object(verify_report, "_ACTUAL_MODULE_CACHE", cache):
                with self.assertRaises(verify_report.ActualVerificationError):
                    verify_report._actual_load_module(name)

        require_rejection("unbound", None, {}, "cp2_schema")
        require_rejection("nonallowlisted", copy.deepcopy(binding), {}, "not_allowed")
        for field, replacement in (
            ("sha256", "0" * 64),
            ("size", binding["cp2_schema"]["size"] + 1),
            (
                "mode",
                0o100755
                if binding["cp2_schema"]["mode"] == 0o100644
                else 0o100644,
            ),
        ):
            changed = copy.deepcopy(binding)
            changed["cp2_schema"][field] = replacement
            require_rejection("source-" + field, changed, {}, "cp2_schema")
        stale = mock.Mock()
        stale.__schurvio_source_binding__ = {
            "mode": 0o100644,
            "sha256": "f" * 64,
            "size": 1,
        }
        require_rejection(
            "cached-binding",
            copy.deepcopy(binding),
            {"cp2_schema": stale},
            "cp2_schema",
        )

